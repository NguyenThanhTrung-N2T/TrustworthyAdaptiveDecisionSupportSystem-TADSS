using Microsoft.OpenApi.Any;
using Microsoft.OpenApi.Models;
using Swashbuckle.AspNetCore.SwaggerGen;
using TADSS.Application.Common;
using TADSS.Runtime.Api.Common;

namespace TADSS.Runtime.Api.OpenApi;

/// <summary>
/// OpenAPI operation filter mô tả header và tham số truy vấn của contract (INTEGRATION_SPEC §2, §3.2, §3.5):
/// <c>X-Idempotency-Key</c> bắt buộc ở <c>POST /api/v2/decisions</c>, <c>/override</c>, <c>/outcome</c>; <c>X-Actor-Id</c> bắt buộc ở <c>/override</c>;
/// <c>X-Correlation-ID</c> tùy chọn ở mọi endpoint; <c>branchId</c>/<c>page</c>/<c>pageSize</c> của <c>pending-approvals</c> kèm miền giá trị.
/// </summary>
public class RequiredHeaderOperationFilter : IOperationFilter
{
    private const string CollectionPath = "api/v2/decisions";
    private const string PendingApprovalsPath = "api/v2/decisions/pending-approvals";
    private const string OverridePath = "api/v2/decisions/{decisionId}/override";
    private const string OutcomePath = "api/v2/decisions/{decisionId}/outcome";

    private static readonly string IdempotencyKeyDescription =
        $"Unique client-generated operation key (UUID or string 1..{ContractLimits.MaxIdempotencyKeyLength} chars) for idempotency and safe retry.";

    private static readonly string ActorIdDescription =
        $"Manager identifier (1..{ContractLimits.MaxActorIdLength} Unicode characters) taken by SmashCourt from the authenticated JWT.";

    private const string CorrelationDescription =
        "Distributed tracing correlation ID (UUID or custom tracking string). Auto-generated by TADSS if omitted.";

    public void Apply(OpenApiOperation operation, OperationFilterContext context)
    {
        operation.Parameters ??= new List<OpenApiParameter>();

        var httpMethod = context.ApiDescription.HttpMethod?.ToUpperInvariant();
        var relativePath = context.ApiDescription.RelativePath?.TrimStart('/') ?? string.Empty;
        var isPost = string.Equals(httpMethod, "POST", StringComparison.Ordinal);

        // 1. X-Idempotency-Key: bắt buộc cho đánh giá, override và outcome
        var needsIdempotencyKey = isPost && (IsPath(relativePath, CollectionPath) || IsPath(relativePath, OverridePath) || IsPath(relativePath, OutcomePath));
        if (needsIdempotencyKey)
        {
            SetHeader(operation, HttpHeaderNames.IdempotencyKey, required: true, IdempotencyKeyDescription, new OpenApiSchema
            {
                Type = "string",
                MinLength = 1,
                MaxLength = ContractLimits.MaxIdempotencyKeyLength,
                Example = new OpenApiString("req-booking-20260912-001")
            });
        }

        // 2. X-Actor-Id: bắt buộc cho override
        if (isPost && IsPath(relativePath, OverridePath))
        {
            SetHeader(operation, HttpHeaderNames.ActorId, required: true, ActorIdDescription, new OpenApiSchema
            {
                Type = "string",
                MinLength = 1,
                MaxLength = ContractLimits.MaxActorIdLength,
                Example = new OpenApiString("manager-01")
            });
        }

        // 3. X-Correlation-ID: tùy chọn ở mọi endpoint (tự cấp nếu thiếu)
        SetHeader(operation, HttpHeaderNames.CorrelationId, required: false, CorrelationDescription, new OpenApiSchema
        {
            Type = "string",
            Example = new OpenApiString("018e3a2b-8a71-7000-8c24-998877665544")
        });

        // 4. Hàng chờ duyệt: branchId bắt buộc, page/pageSize có miền giá trị và mặc định của contract
        if (string.Equals(httpMethod, "GET", StringComparison.Ordinal) && IsPath(relativePath, PendingApprovalsPath))
        {
            DescribePendingApprovalsQuery(operation);
        }
    }

    private static bool IsPath(string relativePath, string expected) =>
        string.Equals(relativePath, expected, StringComparison.OrdinalIgnoreCase);

    // Header đã có sẵn (do Swashbuckle sinh từ model) thì chỉnh tại chỗ để giữ thứ tự; chưa có thì thêm mới
    private static void SetHeader(OpenApiOperation operation, string name, bool required, string description, OpenApiSchema schema)
    {
        var existing = operation.Parameters.FirstOrDefault(p => string.Equals(p.Name, name, StringComparison.OrdinalIgnoreCase));
        if (existing is null)
        {
            operation.Parameters.Add(new OpenApiParameter
            {
                Name = name,
                In = ParameterLocation.Header,
                Required = required,
                Description = description,
                Schema = schema
            });
            return;
        }

        existing.Required = required;
        existing.Description = description;
        existing.Schema = schema;
    }

    private static void DescribePendingApprovalsQuery(OpenApiOperation operation)
    {
        foreach (var parameter in operation.Parameters)
        {
            switch (parameter.Name)
            {
                case "branchId":
                    parameter.Required = true;
                    parameter.Description = "Chi nhánh cần lấy hàng chờ duyệt.";
                    break;
                case "page":
                    parameter.Description = "Số trang, bắt đầu từ 1.";
                    parameter.Schema.Minimum = 1;
                    parameter.Schema.Default = new OpenApiInteger(1);
                    break;
                case "pageSize":
                    parameter.Description = $"Số mục mỗi trang, 1..{ContractLimits.MaxPageSize}.";
                    parameter.Schema.Minimum = 1;
                    parameter.Schema.Maximum = ContractLimits.MaxPageSize;
                    parameter.Schema.Default = new OpenApiInteger(ContractLimits.DefaultPageSize);
                    break;
            }
        }
    }
}
