using Microsoft.OpenApi.Any;
using Microsoft.OpenApi.Models;
using Swashbuckle.AspNetCore.SwaggerGen;

namespace TADSS.Runtime.Api.Configuration;

/// <summary>
/// OpenAPI operation filter to document required and optional headers
/// according to API_CONTRACT_V1.md specifications.
/// </summary>
public class RequiredHeaderOperationFilter : IOperationFilter
{
    public void Apply(OpenApiOperation operation, OperationFilterContext context)
    {
        operation.Parameters ??= new List<OpenApiParameter>();

        var httpMethod = context.ApiDescription.HttpMethod?.ToUpperInvariant();
        var relativePath = context.ApiDescription.RelativePath?.TrimStart('/');

        // 1. X-Idempotency-Key: Required for POST /api/v1/decisions (EvaluateDecision)
        var isEvaluateDecision = string.Equals(httpMethod, "POST", StringComparison.OrdinalIgnoreCase) &&
                                 string.Equals(relativePath, "api/v1/decisions", StringComparison.OrdinalIgnoreCase);

        if (isEvaluateDecision)
        {
            var existingIdempotencyParam = operation.Parameters.FirstOrDefault(p =>
                string.Equals(p.Name, "X-Idempotency-Key", StringComparison.OrdinalIgnoreCase));

            if (existingIdempotencyParam != null)
            {
                existingIdempotencyParam.Required = true;
                existingIdempotencyParam.Description = "Unique client-generated operation key (UUID or string 1..128 chars) for idempotency and safe retry.";
                existingIdempotencyParam.Schema = new OpenApiSchema
                {
                    Type = "string",
                    MinLength = 1,
                    MaxLength = 128,
                    Example = new OpenApiString("req-booking-20260912-001")
                };
            }
            else
            {
                operation.Parameters.Add(new OpenApiParameter
                {
                    Name = "X-Idempotency-Key",
                    In = ParameterLocation.Header,
                    Required = true,
                    Description = "Unique client-generated operation key (UUID or string 1..128 chars) for idempotency and safe retry.",
                    Schema = new OpenApiSchema
                    {
                        Type = "string",
                        MinLength = 1,
                        MaxLength = 128,
                        Example = new OpenApiString("req-booking-20260912-001")
                    }
                });
            }
        }

        // 2. X-Correlation-ID: Optional for all endpoints (auto-generated if omitted)
        var existingCorrelationParam = operation.Parameters.FirstOrDefault(p =>
            string.Equals(p.Name, "X-Correlation-ID", StringComparison.OrdinalIgnoreCase));

        if (existingCorrelationParam != null)
        {
            existingCorrelationParam.Required = false;
            existingCorrelationParam.Description = "Distributed tracing correlation ID (UUID or custom tracking string). Auto-generated by TADSS if omitted.";
            existingCorrelationParam.Schema = new OpenApiSchema
            {
                Type = "string",
                Example = new OpenApiString("018e3a2b-8a71-7000-8c24-998877665544")
            };
        }
        else
        {
            operation.Parameters.Add(new OpenApiParameter
            {
                Name = "X-Correlation-ID",
                In = ParameterLocation.Header,
                Required = false,
                Description = "Distributed tracing correlation ID (UUID or custom tracking string). Auto-generated by TADSS if omitted.",
                Schema = new OpenApiSchema
                {
                    Type = "string",
                    Example = new OpenApiString("018e3a2b-8a71-7000-8c24-998877665544")
                }
            });
        }
    }
}
